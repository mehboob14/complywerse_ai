# Helpers used by the seeder to enumerate every reachable trigger.
# ─────────────────────────────────────────────────────────────────────────────
def reachable_trigger_keys() -> list[tuple[str, str]]:
    """Return the list of (resource, verb) PRIMARY_TRIGGER keys that are
    actually reachable via inferTriggerEventFromActionName.

    Verbs not in CRUD_VERBS are coerced to 'update' by the validator, so
    keys like 'governance.documents:upload' / ':approve' / ':reject' are
    NOT reachable from a `platform_action.<verb>.*` node — they're filtered
    out here so the seeder doesn't try to use them.
    """
    out: list[tuple[str, str]] = []
    for key, expected in PRIMARY_TRIGGER.items():
        resource, _, verb = key.partition(":")
        if verb not in CRUD_VERBS:
            continue
        # Some keys are shadowed by an earlier entry in PATH_TO_RESOURCE
        # (e.g. compliance.evidence_requirements is shadowed by compliance.evidence
        # because .startswith() matches the shorter prefix first). Filter those
        # out — they cannot be reached via action_name inference.
        synth = synthesize_action_name(resource, verb)
        if synth and infer_trigger_event_from_action_name(synth) == expected:
            out.append((resource, verb))
    return out


def canonical_module_path_for_resource(resource: str) -> str | None:
    """Find the first prefix in PATH_TO_RESOURCE that maps to `resource`.
    Used by the seeder to synthesize a valid action_name modulePath."""
    for prefix, res in PATH_TO_RESOURCE:
        if res == resource:
            return prefix
    return None


def synthesize_action_name(resource: str, verb: str) -> str | None:
    """Build a platform_action.* string that resolves to (resource, verb).

    The validator splits on '.' and uses parts[2:] as modulePath, then walks
    PATH_TO_RESOURCE longest-first via startswith. So we just need a
    modulePath that starts with the canonical prefix for `resource` AND
    isn't accidentally prefixed by a more-specific entry in the table.
    """
    prefix = canonical_module_path_for_resource(resource)
    if not prefix:
        return None
    candidate = f"platform_action.{verb}.{prefix}"
    # Verify the validator agrees by round-tripping
    if infer_trigger_event_from_action_name(candidate) == PRIMARY_TRIGGER[f"{resource}:{verb}"]:
        return candidate
    # Fall back to appending a synthetic leaf segment
    candidate = f"platform_action.{verb}.{prefix}.event"
    if infer_trigger_event_from_action_name(candidate) == PRIMARY_TRIGGER[f"{resource}:{verb}"]:
        return candidate
    return None
