CRUD_VERBS = ("create", "update", "delete", "trigger")


def infer_trigger_event_from_action_name(action_name: str | None) -> str | None:
    """Mirror of inferTriggerEventFromActionName (types.ts:857-870)."""
    if not action_name or not action_name.startswith("platform_action."):
        return None
    parts = action_name.split(".")
    if len(parts) < 3:
        return None
    verb = parts[1]
    module_path = ".".join(parts[2:])
    resource: str | None = None
    for prefix, res in PATH_TO_RESOURCE:
        if module_path.startswith(prefix):
            resource = res
            break
    if not resource:
        return None
    verb_key = verb if verb in CRUD_VERBS else "update"
    return PRIMARY_TRIGGER.get(f"{resource}:{verb_key}")


def normalize_node_type(node: dict) -> str:
    """Mirror of normalizeBackendNode in page.tsx:69-89.
    Produces the canvas-side nodeType for a backend node row."""
    nt = node.get("node_type") or "action"
    if node.get("is_start") or node.get("node_key") == "start":
        nt = "start"
    if node.get("is_terminal") or node.get("node_key") == "end":
        nt = "end"
    return nt


def get_trigger_event_for_first_node(first_node: dict | None) -> str | None:
    """Mirror of getTriggerEventForFirstNode (types.ts:886-901)."""
    if not first_node:
        return None
    nt = normalize_node_type(first_node)
    cfg = first_node.get("config") or {}
    if nt == "start":
        tt = cfg.get("trigger_type") or ""
        if not tt:
            return None
        return TRIGGER_EVENT_MAP.get(tt, tt)
    if nt == "action":
        return infer_trigger_event_from_action_name(cfg.get("action_name") or "")
    return None


def validate_graph(nodes: list[dict], edges: list[dict]) -> tuple[bool, str, str | None]:
    """Mirror of validateWorkflowGraph (types.ts:924-971).
    Returns (ok, error_message_or_empty, computed_trigger_event_or_None).
    Edges use backend keys: source_node_key / target_node_key.
    """
    if not nodes:
        return False, "Graph has no nodes.", None
    has_work = any(
        n.get("node_key") != "start" and normalize_node_type(n) != "end"
        for n in nodes
    )
    if not has_work:
        return False, "Add at least one node after Start so the workflow has something to do.", None

    start_nodes = [
        n for n in nodes
        if n.get("node_key") == "start"
        or n.get("is_start") is True
        or normalize_node_type(n) == "start"
    ]
    if not start_nodes:
        return False, "Add a Start node to begin the workflow.", None
    start_node = next((n for n in start_nodes if n.get("node_key") == "start"), start_nodes[0])
    sk = start_node.get("node_key")
    start_edges = [e for e in edges if e.get("source_node_key") == sk]
    if not start_edges:
        return False, "Connect the Start node to the first action of your workflow.", None
    if len(start_edges) > 1:
        return False, "Start can only connect to one node. Remove the extra connections.", None
    target_key = start_edges[0].get("target_node_key")
    first_node = next((n for n in nodes if n.get("node_key") == target_key), None)
    if not first_node:
        return False, "The Start connection points to a node that no longer exists.", None
    computed = get_trigger_event_for_first_node(first_node)
    if not computed:
        nt = normalize_node_type(first_node)
        if nt == "action":
            return False, "First action is not a CRUD platform_action eligible for trigger inference.", None
        return False, "First node has no trigger_type configured.", None
    return True, "", computed


