"""Generate artifact content for ONE framework whose catalog entries carry an `evidence` list (UAE IA), several artifacts at a time.

Each artifact is generated by `generate_artifact_content.generate_one` (same modes: document / column template / collection guide, same
sanitizer) but GROUNDED: the prompt also carries what the standard requires in that control's area and the evidence recommendations the
artifact must let the organisation show (`evidence` = evidence names under `control_ref` / `also_controls` in the framework's catalog JSON),
and a document ends with an "Evidence Provided" table. Output file and format are the generator's (seed_data/artifact_content.json, keyed
{framework_key: {artifact_id: {...}}}); it is written whole, atomically, after every artifact under one lock, so the run is resumable: an
artifact that already has current content is skipped.

    cd backend
    $env:PYTHONPATH="."; py -3 -u scripts/generate_grounded_artifact_content.py --framework uae_ia --workers 5
    # options:
    #   --ids UAEIA-001,UAEIA-017   only these artifacts          --limit 3    stop after this many (smoke test)
    #   --force                     regenerate even if present    --model X    override the model (default = the generator's)
    #   --dry-run                   print the first prompts, call nothing   --usage-log F   one JSON line per AI call (tokens, seconds)

Requires a real OpenAI key in backend/.env (as the generator does). Every call goes through the platform's guarded client.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import sys
import threading
import time
from concurrent.futures import ThreadPoolExecutor, as_completed
from datetime import datetime
from pathlib import Path
from types import SimpleNamespace

HERE = Path(__file__).resolve().parent
if str(HERE) not in sys.path:
    sys.path.insert(0, str(HERE))
import generate_artifact_content as gen  # noqa: E402  (loads backend/.env and grc.config: the AI guard and the model-parameter shim)

SEED = HERE.parent / "grc" / "seed_data"


class _Stop(Exception):
    """A dry run reached the AI call."""


class _DryClient:
    """Records the messages generate_one would send, then stops: nothing leaves the machine."""

    def __init__(self):
        self.messages = None
        self.chat = SimpleNamespace(completions=SimpleNamespace(create=self._create))

    def _create(self, **kw):
        self.messages = kw.get("messages")
        raise _Stop()


class _Meter:
    """Wraps the real client; records seconds and token usage of every call (thread-safe)."""

    def __init__(self, client, log_path: str | None):
        self._client, self._log, self._lock = client, log_path, threading.Lock()
        self.calls: list[dict] = []
        self.chat = SimpleNamespace(completions=SimpleNamespace(create=self._create))

    def _create(self, **kw):
        t0 = time.time()
        resp = self._client.chat.completions.create(**kw)
        u = getattr(resp, "usage", None)
        details = getattr(u, "completion_tokens_details", None)
        rec = {"seconds": round(time.time() - t0, 1), "prompt": getattr(u, "prompt_tokens", None),
               "completion": getattr(u, "completion_tokens", None), "reasoning": getattr(details, "reasoning_tokens", None)}
        with self._lock:
            self.calls.append(rec)
            if self._log:
                with open(self._log, "a", encoding="utf-8") as fh:
                    fh.write(json.dumps(rec) + "\n")
        return resp


def _framework_controls(framework_key: str) -> dict:
    registry = json.loads((SEED / "scf" / "crosswalk_registry.json").read_text(encoding="utf-8"))
    entry = next((e for e in registry["frameworks"] if e.get("slug") == framework_key), None)
    if not entry or not entry.get("file"):
        raise SystemExit(f"{framework_key}: not in crosswalk_registry.json, so its framework file is unknown")
    data = json.loads((SEED / "frameworks" / entry["file"]).read_text(encoding="utf-8"))
    return {c["control_id"]: c for c in data["controls"]}


def _grounded(art: dict, controls: dict) -> dict:
    """The artifact plus `evidence_items` (name + description of the evidence it provides) and `requirement` (the control text)."""
    control_ids = [art["control_ref"]] + list(art.get("also_controls") or [])
    unknown = [c for c in control_ids if c not in controls]
    if unknown:
        raise SystemExit(f"{art['artifact_id']}: unknown control(s) {unknown}")
    by_name: dict = {}
    for cid in control_ids:
        for e in controls[cid].get("evidence_requirements") or []:
            by_name.setdefault(e["name"], e)
    names = art.get("evidence") or []
    missing = [n for n in names if n not in by_name]
    if missing:
        raise SystemExit(f"{art['artifact_id']}: evidence not found under {control_ids}: {missing}")
    requirement = "\n\n".join((controls[cid].get("full_text") or controls[cid].get("description") or "").strip() for cid in control_ids)
    return {**art, "evidence_items": [{"name": n, "description": _no_ids(by_name[n].get("description", ""))} for n in names],
            "requirement": _no_ids(requirement).strip()}


_ID_REF = re.compile(r"\s*\((?:refer to|see|per)\s+[MT]\.?\d\.\d(?:\.\d+)?(?:\s*(?:,|and)\s*[MT]\.?\d\.\d(?:\.\d+)?)*\)", re.I)
_ID = re.compile(r"\b[MT]\.?\d\.\d(?:\.\d+)?\b")


def _no_ids(text: str) -> str:
    """The generator forbids control references in the documents: keep UAE IA control ids ("refer to M1.2.2") out of the prompt too, also
    the standard's own misprint "T.3.2.3" in the malware control and its "(see also M2.3)" in the risk treatment control."""
    return _ID.sub("the related control", _ID_REF.sub("", text or ""))


def _write(content: dict) -> None:
    tmp = gen._CONTENT.with_suffix(".json.tmp")
    tmp.write_text(json.dumps(content, ensure_ascii=False, indent=1), encoding="utf-8")
    for attempt in range(20):   # Windows: another process (a reader, an indexer) can hold the target open for a moment
        try:
            os.replace(tmp, gen._CONTENT)
            return
        except PermissionError:
            if attempt == 19:
                raise
            time.sleep(0.5)


def main() -> None:
    ap = argparse.ArgumentParser(description="Generate evidence-grounded artifact content for one framework (resumable, parallel).")
    ap.add_argument("--framework", required=True, help="framework key in artifact_catalog.json and slug in crosswalk_registry.json (uae_ia)")
    ap.add_argument("--workers", type=int, default=4)
    ap.add_argument("--ids")
    ap.add_argument("--limit", type=int, default=0)
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--model", default=os.environ.get("ARTIFACT_GEN_MODEL") or gen.get_openai_model())
    ap.add_argument("--dry-run", action="store_true")
    ap.add_argument("--usage-log")
    args = ap.parse_args()
    for stream in (sys.stdout, sys.stderr):
        try:
            stream.reconfigure(encoding="utf-8", errors="replace")
        except Exception:  # noqa: BLE001
            pass

    catalog = json.loads(gen._CATALOG.read_text(encoding="utf-8"))
    if args.framework not in catalog:
        raise SystemExit(f"{args.framework}: not in artifact_catalog.json")
    fw = catalog[args.framework]
    fw_name = fw.get("name", args.framework)
    controls = _framework_controls(args.framework)
    only = {x.strip() for x in (args.ids or "").split(",") if x.strip()}
    content = json.loads(gen._CONTENT.read_text(encoding="utf-8")) if gen._CONTENT.exists() else {}
    bucket = content.get(args.framework, {})

    todo = []
    for art in fw.get("artifacts", []):
        aid = art.get("artifact_id")
        if not aid or (only and aid not in only):
            continue
        if not art.get("evidence"):
            raise SystemExit(f"{aid}: no `evidence` list: this tool is for catalogs built from their evidence recommendations")
        if not args.force and gen._is_current(bucket.get(aid, {}), art):
            continue
        todo.append(_grounded(art, controls))
    if args.limit:
        todo = todo[:args.limit]
    print(f"[grounded-gen] framework={args.framework} model={args.model} workers={args.workers} | to generate: {len(todo)} "
          f"(already done: {len(bucket)}/{len(fw.get('artifacts', []))})", flush=True)

    if args.dry_run:
        for art in todo[:3]:
            dry = _DryClient()
            try:
                gen.generate_one(dry, fw_name, art, args.model)
            except _Stop:
                pass
            print(f"\n===== {art['artifact_id']} {art['name']} ({art['type']}, {art['format']}) =====")
            for m in dry.messages or []:
                print(f"--- {m['role']} ---\n{m['content']}")
        return

    if not gen._ai_available():
        raise SystemExit("No usable OpenAI key — set AI_INTEGRATIONS_OPENAI_API_KEY / OPENAI_API_KEY in backend/.env")
    meter = _Meter(gen._client(), args.usage_log)
    lock = threading.Lock()
    done = failed = 0
    started = time.time()

    def work(art: dict) -> tuple[dict, dict]:
        last: Exception | None = None
        for attempt in range(3):
            try:
                return art, gen.generate_one(meter, fw_name, art, args.model)
            except Exception as exc:  # noqa: BLE001
                last = exc
                time.sleep(15 * (attempt + 1))
        raise last  # type: ignore[misc]

    with ThreadPoolExecutor(max_workers=max(1, args.workers)) as pool:
        futures = {pool.submit(work, a): a for a in todo}
        for fut in as_completed(futures):
            art = futures[fut]
            aid = art["artifact_id"]
            try:
                _, res = fut.result()
            except Exception as exc:  # noqa: BLE001
                failed += 1
                print(f"[FAIL] {args.framework}/{aid}: {exc}", file=sys.stderr, flush=True)
                continue
            with lock:
                done += 1
                content.setdefault(args.framework, bucket)
                bucket[aid] = {"title": art.get("name"), "type": art.get("type"), "control_ref": art.get("control_ref"),
                               "format": art.get("format"), "content": res["content"], "content_format": res["content_format"],
                               "table": res.get("table"), "model": args.model, "generated_at": datetime.utcnow().isoformat()}
                _write(content)
                print(f"[{done + failed}/{len(todo)}] {args.framework}/{aid} ({art.get('type')} -> {res['content_format']}, "
                      f"{len(res['content'])} chars) {(art.get('name') or '')[:50]}  [{int(time.time() - started)}s]", flush=True)

    calls = meter.calls
    tot = lambda k: sum(c[k] or 0 for c in calls)  # noqa: E731
    print(f"\nDone. generated={done} failed={failed} | {len(calls)} AI calls, {int(time.time() - started)}s wall; tokens: prompt={tot('prompt')} "
          f"completion={tot('completion')} (of which reasoning={tot('reasoning')}); mean {sum(c['seconds'] for c in calls) / max(1, len(calls)):.0f}s per call", flush=True)
    print(f"Content written to {gen._CONTENT}", flush=True)


if __name__ == "__main__":
    main()
