"""Connect Wizard — one-liner customer onboarding.

Flow:
  1. Authenticated customer hits POST /connect-wizard/issue-token
     → backend signs a JWT (15-min TTL) with their tenant_id
  2. Customer's browser polls GET /connect-wizard/status/{token}
  3. Customer runs the one-liner script on their Windows server. The
     script is served by GET /connect-wizard/win/{token} (returns
     PowerShell that does setup + POSTs handshake back).
  4. The script's last step POSTs to /connect-wizard/handshake which
     creates an IntegrationConnection row for the tenant.
  5. Browser poll picks up "ready" status and redirects to dashboard.

Security:
  - Token is signed with SESSION_SECRET, includes tenant_id + nonce + exp.
  - Handshake includes one-time agent password generated by the script
    (random per machine, never echoed back to the customer).
  - Connection rows are stored with credentials encrypted via Fernet
    (existing per-tenant encryption used elsewhere in the platform).
"""
from __future__ import annotations

import logging
import os
import secrets
import time

logger = logging.getLogger(__name__)
from datetime import datetime
from typing import Optional

import jwt
from fastapi import APIRouter, Depends, HTTPException, Request, Response, status
from fastapi.responses import PlainTextResponse
from pydantic import BaseModel
from sqlalchemy import func
from sqlalchemy.orm import Session

from grc.crypto import encrypt_secret
from grc.models import IntegrationConnection, get_db, ITAsset
from grc.routers.auth_router import get_user_primary_tenant, require_auth, GRCUser

router = APIRouter(prefix="/connect-wizard", tags=["Connect Wizard"])

SESSION_SECRET = os.environ.get("SESSION_SECRET", "dev-secret")
TOKEN_TTL_SECONDS = 60 * 60  # 60 minutes — gives operators headroom for
                              # first-time WinRM/SSH setup on the target before
                              # the handshake fires. Was 15 min, which expired
                              # mid-config for anyone reading the docs while
                              # configuring the target's auth/firewall/cert.

# Hints rendered to the operator in the wizard UI when pre-flight rejects
# their credentials. Keep these in one place so we don't drift between
# the API and the React error banner.
_PREFLIGHT_HINTS = {
    "auth_failed": (
        "The username or password is wrong. For Windows: confirm the service "
        "account exists, is NOT locked, and that you typed the exact password "
        "set on the local account (Set-LocalUser as Admin if you reset it). "
        "For Linux: confirm the user can `ssh user@host` from a terminal first. "
        "For AWS: re-paste the access key + secret from the IAM console."
    ),
    "network_unreachable": (
        "The scanner cannot reach the target. For Windows: run "
        "`Test-NetConnection <host> -Port 5986` from this server. For Linux: "
        "run `nc -zv <host> 22`. Check firewall + that the service is running."
    ),
    "ssl_error": (
        "TLS handshake failed. The wizard auto-trusts self-signed certs, so "
        "this usually means the WinRM listener is HTTP-only (port 5985), not "
        "HTTPS (5986). Re-run the wizard installer to set up the HTTPS listener "
        "or switch the connection to HTTP."
    ),
    "config_error": (
        "A required field was missing or the runtime is misconfigured. "
        "Check that hostname, username, and password are all filled in."
    ),
    "unknown": (
        "Something went wrong during pre-flight. Check the server logs and "
        "verify the target host is reachable + the service account works."
    ),
}


# ─── Models ──────────────────────────────────────────────────────────────────

class IssueTokenIn(BaseModel):
    platform: str  # "windows" | "linux" | "aws"


class HandshakeIn(BaseModel):
    tenant_token: str
    hostname: str
    display_label: Optional[str] = None   # operator-friendly name for the UI
    os_name: Optional[str] = None
    winrm_endpoint: Optional[str] = None
    ssh_endpoint: Optional[str] = None
    service_account: Optional[str] = None
    agent_password: Optional[str] = None
    cert_fingerprint: Optional[str] = None
    # CIS Module Updated — when the operator clicks "Connect" on an
    # asset row in /assets, the wizard URL carries `?asset_id=N`. We
    # forward it here so the backend can bind the new connection
    # DIRECTLY to that asset row, instead of relying on the host_name
    # fallback match (which breaks when the operator types IP vs FQDN).
    asset_id: Optional[int] = None
    # ─── Extended platforms (banks: MSSQL/Postgres/MySQL/AD/Azure/K8s) ──
    # Optional, only present when the operator picks one of the new
    # platforms in the Connect Wizard. The handshake handler reads only
    # the fields relevant to the chosen platform.
    database_name: Optional[str] = None          # SQL DBs (mssql/postgres/mysql)
    db_port: Optional[int] = None                # SQL DBs (overrides default 1433/5432/3306)
    # Oracle uses TNS service name OR SID instead of a generic database name.
    # The runner accepts either — service_name preferred; SID is the legacy
    # form on older installs (Oracle 11g and earlier defaults like ORCL/XE).
    oracle_service_name: Optional[str] = None    # Oracle (preferred over SID)
    oracle_sid: Optional[str] = None             # Oracle (alternative to service_name)
    ldap_bind_dn: Optional[str] = None           # AD/LDAP bind DN
    ldap_use_ssl: Optional[bool] = None          # AD/LDAP — true for ldaps:// (port 636)
    azure_subscription_id: Optional[str] = None  # Azure
    azure_tenant_id: Optional[str] = None        # Azure
    azure_client_id: Optional[str] = None        # Azure
    azure_client_secret: Optional[str] = None    # Azure
    kubeconfig: Optional[str] = None             # Kubernetes (YAML blob)
    k8s_server: Optional[str] = None             # Kubernetes (alt: server+token+ca)
    k8s_token: Optional[str] = None              # Kubernetes
    k8s_ca_cert: Optional[str] = None            # Kubernetes


# In-memory status store. Production would use Redis; for v1 this is fine
# because tokens are short-lived and a process restart only invalidates
# the wizard session (customer just clicks "Connect" again).
_STATUS: dict[str, dict] = {}


def _sign(payload: dict) -> str:
    return jwt.encode(payload, SESSION_SECRET, algorithm="HS256")


def _verify(token: str) -> dict:
    try:
        return jwt.decode(token, SESSION_SECRET, algorithms=["HS256"])
    except jwt.PyJWTError as e:
        raise HTTPException(401, f"Invalid token: {e}")


# ─── Endpoints ───────────────────────────────────────────────────────────────

@router.post("/issue-token")
def issue_token(
    body: IssueTokenIn,
    db: Session = Depends(get_db),
    current_user: GRCUser = Depends(require_auth),
):
    """Issue a short-lived signed token for the wizard handshake.

    Frontend calls this when the customer picks a platform in the wizard.
    The token gets embedded in the one-liner script URL.
    """
    # cisco + oracle added so the agentless quick-start covers network
    # devices and DB targets, not just OS hosts. The /handshake endpoint
    # already handles ssh_endpoint + sql_endpoint fields, so the only
    # backend gate that needed widening was this validator.
    # Banking-relevant additions: mssql/postgres/mysql DBs, AD/LDAP, Azure
    # cloud, Kubernetes. Each one has a registered runner; the handshake
    # path stores the supplied credentials in an IntegrationConnection and
    # the credentials.py picker dispatches by integration_type.
    _allowed_platforms = {
        "windows", "linux", "aws", "digitalocean", "cisco", "oracle",
        "mssql", "postgres", "mysql", "ad", "azure", "k8s",
    }
    if body.platform not in _allowed_platforms:
        raise HTTPException(
            422,
            f"platform must be one of: {', '.join(sorted(_allowed_platforms))}",
        )
    tenant_id = get_user_primary_tenant(current_user, db)
    nonce = secrets.token_urlsafe(16)
    now = int(time.time())
    payload = {
        "tenant_id": tenant_id,
        "user_id": current_user.id,
        "platform": body.platform,
        "nonce": nonce,
        "iat": now,
        "exp": now + TOKEN_TTL_SECONDS,
    }
    token = _sign(payload)
    _STATUS[nonce] = {"state": "pending", "platform": body.platform, "tenant_id": tenant_id}
    return {
        "token": token,
        "nonce": nonce,
        "expires_in": TOKEN_TTL_SECONDS,
        "script_url": f"/grc/connect-wizard/{body.platform}/{token}",
    }


@router.get("/status/{nonce}")
def get_status(
    nonce: str,
    current_user: GRCUser = Depends(require_auth),
    db: Session = Depends(get_db),
):
    """Frontend polls this every ~3s while showing the one-liner. When the
    customer's machine POSTs to /handshake, this flips to ready."""
    rec = _STATUS.get(nonce)
    if not rec:
        raise HTTPException(404, "Unknown nonce or token expired")
    # Tenant scope check
    tenant_id = get_user_primary_tenant(current_user, db)
    if rec.get("tenant_id") != tenant_id:
        raise HTTPException(403, "Cross-tenant nonce access forbidden")
    return rec


@router.get("/windows/{token}", response_class=PlainTextResponse)
def windows_script(token: str):
    """Return the PowerShell one-liner installer with the tenant token baked in.

    Customer runs as Administrator. Script enables WinRM, creates a read-only
    PER-TENANT service account named ``complivrs_t{tenant_id}`` so two tenants
    connecting to the same machine cannot clobber each other's credentials.

    NOTE: served as text/plain so `iwr ... | iex` works in PowerShell.
    """
    payload = _verify(token)
    if payload.get("platform") != "windows":
        raise HTTPException(400, "Token is not for windows platform")
    handshake_url = "http://localhost:5000/grc/connect-wizard/handshake"
    return _build_windows_script(token, handshake_url, payload["tenant_id"])


