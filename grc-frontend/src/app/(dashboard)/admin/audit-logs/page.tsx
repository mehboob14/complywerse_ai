function UserAvatar({ name }: { name: string }) {
  const initials = name
    .split(/\s+/)
    .map((n) => n[0] ?? '')
    .join('')
    .toUpperCase()
    .slice(0, 2) || '?';
  return (
    <span className="inline-flex items-center justify-center w-7 h-7 rounded-full bg-primary-100 text-primary-700 text-xs font-semibold shrink-0 select-none">
      {initials}
    </span>
  );
}

